############################################################
# 利用逆变换法(Inverse Transform Method)
# 产生 Logarithmic(theta) 分布随机样本
#
# 概率质量函数：
#
#            theta^k
# P(X=k) = - ---------
#          log(1-theta) * k
#
# k = 1,2,3,...
# 0 < theta < 1
############################################################

# 自定义函数：
# n      : 样本容量
# theta  : 分布参数
rlogarithmic = function(n, theta)
{
  ########################################################
  # Step 1: 产生 n 个 U(0,1) 随机数
  # 逆变换法的起点
  ########################################################
  u = runif(n)
  
  ########################################################
  # Step 2: 设置CDF初始长度
  #
  # Logarithmic分布支持集为：
  # {1,2,3,...}
  #
  # 理论上要计算到无穷大
  # 实际计算时先取一个足够大的N
  ########################################################
  N = ceiling(-16 / log10(theta))
  
  ########################################################
  # k = 1,2,...,N
  ########################################################
  k = 1:N
  
  ########################################################
  # 归一化常数
  #
  # a = -1/log(1-theta)
  ########################################################
  a = -1/log(1-theta)
  
  ########################################################
  # Step 3: 计算概率质量函数 PMF
  #
  # fk[k] = P(X=k)
  #
  # 使用log形式计算可以提高数值稳定性：
  #
  # P(X=k)
  # = a * theta^k / k
  #
  # 写成：
  #
  # exp(log(a)+k*log(theta)-log(k))
  #
  # 避免 theta^k 很小时发生下溢
  ########################################################
  fk = exp(log(a) + k * log(theta) - log(k))
  
  ########################################################
  # Step 4: 构造CDF
  #
  # Fk[i]
  # = P(X <= i)
  #
  # cumsum() 表示累计求和
  ########################################################
  Fk = cumsum(fk)
  
  ########################################################
  # 创建结果向量
  ########################################################
  x = integer(n)
  
  ########################################################
  # Step 5: 对每个U进行逆变换
  ########################################################
  for (i in 1:n)
  {
    ####################################################
    # 统计有多少个CDF值小于u[i]
    #
    # 离散逆变换法：
    #
    # X = min{k : F(k) >= U}
    #
    # 这里采用等价实现：
    #
    # X = sum(U > F(k)) + 1
    ####################################################
    x[i] = as.integer(sum(u[i] > Fk))
    
    ####################################################
    # 如果x[i] == N
    #
    # 说明当前CDF长度不够
    # 还没有覆盖到该u
    #
    # 需要继续扩展CDF
    ####################################################
    while (x[i] == N)
    {
      ################################################
      # 计算P(X=N+1)
      ################################################
      logf =
        log(a) +
        (N+1)*log(theta) -
        log(N+1)
      
      ################################################
      # 添加新的概率值
      ################################################
      fk = c(fk, exp(logf))
      
      ################################################
      # 更新CDF
      #
      # F(N+1)=F(N)+P(X=N+1)
      ################################################
      Fk = c(Fk, Fk[N] + fk[N+1])
      
      ################################################
      # 更新长度
      ################################################
      N = N + 1
      
      ################################################
      # 重新判断落在哪个区间
      ################################################
      x[i] = as.integer(sum(u[i] > Fk))
    }
    
    ####################################################
    # 一般不会进入while
    # 因为N已经取很大
    ####################################################
  }
  
  ########################################################
  # 返回结果
  #
  # 因为sum(U>Fk)得到的是：
  #
  # 0,1,2,...
  #
  # 而Logarithmic分布支持集是：
  #
  # 1,2,3,...
  #
  # 所以需要整体加1
  ########################################################
  x + 1
}

############################################################
# 产生样本
############################################################

n = 1000
theta = 0.5

# 生成1000个Logarithmic(0.5)随机数
x = rlogarithmic(n, theta)

# 查看样本
x

############################################################
# 计算理论概率
############################################################

# 提取样本中出现过的取值
k = sort(unique(x))

############################################################
# 计算理论PMF
#
# P(X=k)
# = -1/log(1-theta) * theta^k / k
############################################################
p = -1 / log(1 - theta) * theta^k / k

############################################################
# 计算频率标准误
#
# 对每个k:
#
# I(X=k) ~ Bernoulli(p)
#
# 因此频率的标准误：
#
# sqrt(p(1-p)/n)
############################################################
se = sqrt(p*(1-p)/n)

############################################################
# 比较：
#
# 第一行：模拟频率
# 第二行：理论概率
# 第三行：标准误
############################################################
round(
  rbind(
    table(x)/n,
    p,
    se
  ),
  3
)